"""Промпты четырёх стратегий решения логической задачи (команда /logictask)."""

LOGIC_TASK = (
    "Задача. В партии «Переправа» фермеру нужно перевезти через реку волка, козу и капусту. "
    "Лодка вмещает фермера и не более одного из трёх «грузов». "
    "Нельзя оставлять волка наедине с козой, а козу — наедине с капустой. "
    "Как перевезти всё на другой берег за минимальное число рейсов?"
)

DIRECT_SYSTEM_MESSAGE = "Ты решаешь логические задачи. Отвечай точно и по существу."

ANSWER_ONLY_INSTRUCTION = (
    "Ответ должен содержать только ответ — без решения, без шагов, без выводов. Только ответ."
)


def build_direct_prompts() -> tuple[str, str]:
    """Стратегия 1: задача с жёстким условием «только ответ»."""
    return DIRECT_SYSTEM_MESSAGE, f"{LOGIC_TASK}\n\n{ANSWER_ONLY_INSTRUCTION}"


STEPWISE_SYSTEM_MESSAGE = "Ты аккуратный решатель задач."

STEPWISE_INSTRUCTION = (
    "Реши задачу пошагово: разбей решение на отдельные шаги и обоснуй каждый шаг. "
    "В конце дай краткий итоговый ответ."
)


def build_stepwise_prompts() -> tuple[str, str]:
    """Стратегия 2: задача с инструкцией решать пошагово."""
    return STEPWISE_SYSTEM_MESSAGE, f"{LOGIC_TASK}\n\n{STEPWISE_INSTRUCTION}"


COMPOSE_SYSTEM_MESSAGE = "Ты — эксперт по составлению промптов для языковых моделей."

COMPOSE_INSTRUCTION = (
    "Составь промпт, который обеспечит максимально надёжное решение следующей задачи. "
    "Напиши только текст самого промпта, без пояснений.\n\n"
    f"{LOGIC_TASK}"
)


def build_prompt_compose_prompts() -> tuple[str, str]:
    """Стратегия 3, шаг 1: просим модель составить промпт для решения задачи."""
    return COMPOSE_SYSTEM_MESSAGE, COMPOSE_INSTRUCTION


def build_solve_with_prompt_prompts(composed_prompt: str) -> tuple[str, str]:
    """Стратегия 3, шаг 2: решаем задачу промптом, составленным моделью."""
    return composed_prompt, LOGIC_TASK


EXPERT_ROLES = (
    "Ты — шеф-повар, эксперт по точному следованию рецептам и дисциплине шагов.",
    "Ты — психолог животных, специалист по взаимоотношениям животных между собой и с людьми.",
    "Ты — специалист по теории игр, эксперт по формальным стратегиям и конфликтным ситуациям.",
)


def build_expert_prompts(expert_role: str) -> tuple[str, str]:
    """Стратегия 4: решение от одного фиксированного эксперта."""
    return expert_role, LOGIC_TASK


